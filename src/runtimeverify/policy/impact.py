"""
Policy Impact "What-If" Replay Simulator for RuntimeVerify (Sprint 4).
Simulates new or modified deterministic security policies against historical agent telemetry traces
to evaluate delta block rates, false-positive risk, and impact before production deployment.
"""

import json
import logging
from pathlib import Path
from typing import Any, Dict, List, Optional, Union

from pydantic import BaseModel, ConfigDict, Field

from runtimeverify.events.base import Event
from runtimeverify.events.canonical import (
    FilesystemDeleteEvent,
    FilesystemReadEvent,
    FilesystemWriteEvent,
    NetworkRequestEvent,
    ShellCommandEvent,
)
from runtimeverify.policy.evaluator import PolicyEvaluator
from runtimeverify.policy.loader import load_policy_from_yaml
from runtimeverify.policy.models import Policy, PolicySet
import yaml

logger = logging.getLogger(__name__)


class ActionImpactItem(BaseModel):
    """Details of an individual action affected by policy simulation."""

    model_config = ConfigDict(frozen=True)

    action_index: int
    event_type: str
    target: str
    agent_id: str
    session_id: str
    baseline_decision: str
    simulated_decision: str
    reason: str
    policy_id: Optional[str] = None


class PolicyImpactReport(BaseModel):
    """Comprehensive impact analysis report generated by simulating candidate policies."""

    model_config = ConfigDict(frozen=True)

    policy_id: str = Field(..., description="ID of simulated candidate policy")
    total_events_evaluated: int = Field(0, description="Total historical events processed")
    baseline_allowed: int = Field(0, description="Actions allowed under baseline")
    baseline_blocked: int = Field(0, description="Actions blocked under baseline")
    simulated_allowed: int = Field(0, description="Actions allowed under candidate policy")
    simulated_blocked: int = Field(0, description="Actions blocked under candidate policy")
    newly_blocked_count: int = Field(0, description="Actions previously allowed that are now blocked")
    newly_allowed_count: int = Field(0, description="Actions previously blocked that are now allowed")
    delta_block_rate_pct: float = Field(0.0, description="Percentage change in block rate")
    affected_agents: List[str] = Field(default_factory=list, description="Unique agents impacted")
    impacted_actions: List[ActionImpactItem] = Field(
        default_factory=list,
        description="Sample of newly blocked or altered actions",
    )


class PolicyImpactAnalyzer:
    """
    Simulation engine replaying traces against candidate policies to predict production impact.
    """

    def __init__(self, baseline_evaluator: Optional[PolicyEvaluator] = None) -> None:
        self.baseline_evaluator = baseline_evaluator or PolicyEvaluator()

    @staticmethod
    def _parse_event_from_dict(d: Dict[str, Any]) -> Event:
        """Parses a generic dictionary into a typed CanonicalEvent."""
        etype = d.get("event_type", "generic")
        sid = d.get("session_id", "sim-session")
        aid = d.get("agent_id", "sim-agent")
        target = d.get("target", "")

        if etype == "shell.command":
            return ShellCommandEvent(
                session_id=sid,
                agent_id=aid,
                command=d.get("command") or target,
                target=target or d.get("command", "sh"),
                payload=d,
            )
        elif etype == "network.request":
            return NetworkRequestEvent(
                session_id=sid,
                agent_id=aid,
                url=d.get("url") or target,
                target=target or d.get("url", ""),
                method=d.get("method", "GET"),
            )
        elif etype == "filesystem.write":
            return FilesystemWriteEvent(
                session_id=sid,
                agent_id=aid,
                path=d.get("path") or target,
                target=target or d.get("path", ""),
            )
        elif etype == "filesystem.delete":
            return FilesystemDeleteEvent(
                session_id=sid,
                agent_id=aid,
                path=d.get("path") or target,
                target=target or d.get("path", ""),
            )
        elif etype == "filesystem.read":
            return FilesystemReadEvent(
                session_id=sid,
                agent_id=aid,
                path=d.get("path") or target,
                target=target or d.get("path", ""),
            )
        else:
            return Event(
                session_id=sid,
                agent_id=aid,
                event_type=etype,
                target=target,
                payload=d,
            )

    def simulate(
        self,
        candidate_policy: Union[Policy, PolicySet],
        traces: List[Union[Event, Dict[str, Any]]],
    ) -> PolicyImpactReport:
        """
        Simulates candidate policy against a list of events or raw trace dictionaries.
        """
        if isinstance(candidate_policy, Policy):
            policy_id = candidate_policy.id
            pset = PolicySet(name=candidate_policy.id, policies=[candidate_policy])
            candidate_evaluator = PolicyEvaluator(policy_set=pset)
        elif isinstance(candidate_policy, PolicySet):
            policy_id = candidate_policy.name or "policy-set"
            candidate_evaluator = PolicyEvaluator(policy_set=candidate_policy)
        else:
            raise TypeError(f"Expected Policy or PolicySet, got {type(candidate_policy)}")

        total = len(traces)
        b_allow = 0
        b_block = 0
        s_allow = 0
        s_block = 0
        newly_blocked: List[ActionImpactItem] = []
        newly_allowed: int = 0
        affected_agents: set[str] = set()

        session_history: List[str] = []

        for idx, item in enumerate(traces):
            event = item if isinstance(item, Event) else self._parse_event_from_dict(item)

            # Evaluate baseline
            b_dec = self.baseline_evaluator.evaluate(event, session_history=session_history)
            # Evaluate candidate
            s_dec = candidate_evaluator.evaluate(event, session_history=session_history)

            b_status = b_dec.decision.value if hasattr(b_dec.decision, "value") else str(b_dec.decision)
            s_status = s_dec.decision.value if hasattr(s_dec.decision, "value") else str(s_dec.decision)

            if b_status == "ALLOW":
                b_allow += 1
            else:
                b_block += 1

            if s_status == "ALLOW":
                s_allow += 1
            else:
                s_block += 1

            if b_status == "ALLOW" and s_status == "BLOCK":
                affected_agents.add(event.agent_id)
                newly_blocked.append(
                    ActionImpactItem(
                        action_index=idx,
                        event_type=str(event.event_type),
                        target=event.target,
                        agent_id=event.agent_id,
                        session_id=event.session_id,
                        baseline_decision=b_status,
                        simulated_decision=s_status,
                        reason=s_dec.reason or "Blocked by candidate policy",
                        policy_id=s_dec.policy_id,
                    )
                )
            elif b_status == "BLOCK" and s_status == "ALLOW":
                newly_allowed += 1

            # Append to history for temporal rules
            session_history.append(event.target or str(event.event_type))

        delta_rate = ((s_block - b_block) / total * 100.0) if total > 0 else 0.0

        return PolicyImpactReport(
            policy_id=policy_id,
            total_events_evaluated=total,
            baseline_allowed=b_allow,
            baseline_blocked=b_block,
            simulated_allowed=s_allow,
            simulated_blocked=s_block,
            newly_blocked_count=len(newly_blocked),
            newly_allowed_count=newly_allowed,
            delta_block_rate_pct=round(delta_rate, 2),
            affected_agents=sorted(affected_agents),
            impacted_actions=newly_blocked[:50],  # Keep top 50 in report
        )

    def simulate_from_files(self, policy_path: str, traces_path: str) -> PolicyImpactReport:
        """Loads policy and traces from disk and runs simulation."""
        policy_file = Path(policy_path)
        traces_file = Path(traces_path)

        if not policy_file.exists():
            raise FileNotFoundError(f"Policy file not found: {policy_path}")
        if not traces_file.exists():
            raise FileNotFoundError(f"Traces file not found: {traces_path}")

        with open(policy_file, "r", encoding="utf-8") as f:
            raw_policy = yaml.safe_load(f)

        if isinstance(raw_policy, dict) and "policies" not in raw_policy and "id" in raw_policy:
            policy_or_set: Union[Policy, PolicySet] = Policy.model_validate(raw_policy)
        else:
            policy_or_set = load_policy_from_yaml(str(policy_file))

        with open(traces_file, "r", encoding="utf-8") as f:
            raw_traces = json.load(f)

        if not isinstance(raw_traces, list):
            raise ValueError(f"Traces file must contain a JSON list of events/actions, got {type(raw_traces)}")

        return self.simulate(policy_or_set, raw_traces)
